"""Shared detection types.

Every detector returns a list of Detection objects. A Detection carries the
framework mappings (OWASP LLM Top 10 2025, OWASP Top 10 for Agentic
Applications 2026, MITRE ATLAS) so downstream events are SIEM-ready without
any enrichment step.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

Direction = Literal["inbound", "outbound"]

# Where a piece of inspected text came from. The source decides which
# detectors run and how a hit is classified (direct vs indirect injection).
Source = Literal[
    "user",  # end-user turn
    "system",  # operator-authored (trusted role)
    "assistant",  # prior model turn replayed in the conversation history
    "tool_result",  # output of a tool/function call: untrusted data
    "document",  # content submitted for embedding: untrusted data
    "tool_definition",  # tool name/description/schema offered to the model
    "model_output",  # text generated by the model
    "tool_call",  # arguments of a tool call generated by the model
]

# Sources that carry third-party data rather than the caller's own words.
# An injection found here is indirect prompt injection (AML.T0051.001).
INDIRECT_SOURCES = frozenset({"tool_result", "document"})

MAX_EVIDENCE_LEN = 80


@dataclass
class Detection:
    detector: str
    rule_id: str
    severity: int  # 1-10, aligned with the policy block/flag thresholds
    confidence: float  # 0.0-1.0
    description: str
    evidence: str = ""
    owasp_llm: str | None = None
    atlas: str | None = None
    tags: list[str] = field(default_factory=list)
    owasp_agentic: str | None = None
    # Filled in by the pipeline: where the hit was found.
    source: str | None = None
    index: int | None = None
    tool_name: str | None = None
    # detected (default) or redacted (span was masked and traffic continued).
    disposition: str = "detected"

    def __post_init__(self) -> None:
        # Evidence is stored truncated so raw prompts/secrets never land in
        # events at full length; secret detectors additionally mask values.
        if len(self.evidence) > MAX_EVIDENCE_LEN:
            self.evidence = self.evidence[:MAX_EVIDENCE_LEN] + "..."


def mask(value: str, keep: int = 4) -> str:
    """Mask a sensitive value, keeping a short identifying prefix."""
    if len(value) <= keep:
        return "*" * len(value)
    return value[:keep] + "*" * min(len(value) - keep, 12)
